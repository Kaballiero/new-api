func TestMigratedLiteralHTTPResponses(t *testing.T) {
	require.NoError(t, i18n.Init())
	writer := identityhttp.NewWriter(identityhttp.Foreign{
		EmailTaken: func(error) bool { return false }, ProtocolError: func(error) bool { return false }, RecordMissing: func(error) bool { return false },
	}, func(context.Context, string) {})
	cases := []struct {
		name          string
		write         func(*gin.Context, error)
		err           error
		status        int
		code, message string
	}{
		{"catalog create name", cataloghttp.WriteError, catalog.ErrModelNameEmpty, 400, "model_name_empty", "模型名称不能为空"},
		{"catalog update name", cataloghttp.WriteError, catalog.ErrModelNameRequired, 200, "", "模型名称不能为空"},
		{"catalog duplicate model", cataloghttp.WriteError, catalog.ErrModelNameExists, 409, "model_name_exists", "模型名称已存在"},
		{"catalog vendor id", cataloghttp.WriteError, catalog.ErrVendorIDMissing, 400, "vendor_id_missing", "缺少供应商 ID"},
		{"catalog vendor empty", cataloghttp.WriteError, catalog.ErrVendorNameEmpty, 400, "vendor_name_empty", "供应商名称不能为空"},
		{"catalog vendor duplicate", cataloghttp.WriteError, catalog.ErrVendorNameExists, 409, "vendor_name_exists", "供应商名称已存在"},
		{"checkin disabled", accountshttp.WriteError, accounts.ErrCheckinDisabled, 200, "", "签到功能未启用"},
		{"checkin duplicate", accountshttp.WriteError, accounts.ErrAlreadyCheckedIn, 200, "", "今日已签到"},
		{"checkin failed", accountshttp.WriteError, accounts.ErrCheckinFailed, 200, "", "签到失败，请稍后重试"},
		{"checkin quota", accountshttp.WriteError, accounts.ErrCheckinQuotaFailed, 200, "", "签到失败：更新额度出错"},
		{"pricing query", pricinghttp.WriteError, pricing.ErrChannelQueryFailed, 500, "", "查询渠道失败"},
		{"pricing upstreams", pricinghttp.WriteError, pricing.ErrNoUpstreams, 200, "", "无有效上游渠道"},
		{"multi key missing", channelshttp.WriteError, channels.ErrMultiKeyChannelNotFound, 200, "", "渠道不存在"},
		{"passkey create", writer.WriteError, identity.ErrPasskeyRecordInvalid, 200, "", "无法创建 Passkey 凭证"},
		{"passkey login", writer.WriteError, identity.ErrPasskeyLoginInvalid, 200, "", "Passkey 登录状态异常"},
		{"passkey disabled", writer.WriteError, identity.ErrPasskeyAccountDisabled, 200, "", "该用户已被禁用"},
	}
	for _, tc := range cases {
		for _, language := range []string{i18n.LangZhCN, i18n.LangZhTW} {
			t.Run(tc.name+"/"+language, func(t *testing.T) {
				response := httptest.NewRecorder()
				c, _ := gin.CreateTestContext(response)
				c.Request = httptest.NewRequest("POST", "/", nil)
				c.Set(string(constant.ContextKeyLanguage), language)
				tc.write(c, tc.err)
				assert.Equal(t, tc.status, response.Code)
				var body struct {
					Success bool   `json:"success"`
					Code    string `json:"code"`
					Message string `json:"message"`
				}
				require.NoError(t, common.Unmarshal(response.Body.Bytes(), &body))
				assert.False(t, body.Success)
				assert.Equal(t, tc.code, body.Code)
				assert.Equal(t, tc.message, body.Message)
			})
		}
	}
}

func TestWeChatLiteralFailureResponses(t *testing.T) {
	require.NoError(t, i18n.Init())
	cases := []struct {
		err     error
		message string
	}{
		{identity.ErrWeChatCodeMissing, "无效的参数"}, {identity.ErrWeChatCodeInvalid, "验证码错误或已过期"},
		{identity.ErrAccountDeleted, "用户已注销"}, {identity.ErrRegistrationDisabled, "管理员关闭了新用户注册"}, {identity.ErrAccountBanned, "用户已被封禁"},
	}
	for _, tc := range cases {
		for _, language := range []string{i18n.LangZhCN, i18n.LangZhTW} {
			t.Run(tc.message+"/"+language, func(t *testing.T) {
				fixture := wechatLiteralFailure{err: tc.err}
				handler := login_wechat.NewHTTP(func() login_wechat.Completion { return fixture }, func(*model.User, *gin.Context) { t.Fatal("failed login must not authenticate") })
				response := httptest.NewRecorder()
				c, _ := gin.CreateTestContext(response)
				c.Request = httptest.NewRequest(http.MethodGet, "/?code=fixture", nil)
				c.Set(string(constant.ContextKeyLanguage), language)
				handler.Handle(c)
				assert.Equal(t, http.StatusOK, response.Code)
				assert.Empty(t, response.Header().Values("Set-Cookie"))
				var body struct {
					Success bool   `json:"success"`
					Message string `json:"message"`
				}
				require.NoError(t, common.Unmarshal(response.Body.Bytes(), &body))
				assert.False(t, body.Success)
				assert.Equal(t, tc.message, body.Message)
			})
		}
	}
}

type wechatLiteralFailure struct{ err error }

func (wechatLiteralFailure) Enabled() bool                  { return true }
func (wechatLiteralFailure) AuthenticatedUser() *model.User { return nil }
func (f wechatLiteralFailure) ExchangeCode(string) error {
	if f.err == identity.ErrWeChatCodeMissing || f.err == identity.ErrWeChatCodeInvalid {
		return f.err
	}
	return nil
}
func (wechatLiteralFailure) InitializeAccount() {}
func (f wechatLiteralFailure) Taken() bool      { return f.err != identity.ErrRegistrationDisabled }
func (wechatLiteralFailure) LoadAccount() error { return nil }
func (f wechatLiteralFailure) AccountID() int {
	if f.err == identity.ErrAccountDeleted {
		return 0
	}
	return 7
}
func (wechatLiteralFailure) RegistrationEnabled() bool  { return false }
func (wechatLiteralFailure) PrepareAccount()            { panic("unexpected account creation") }
func (wechatLiteralFailure) InsertAccount(string) error { panic("unexpected account creation") }
func (f wechatLiteralFailure) AccountEnabled() bool     { return f.err != identity.ErrAccountBanned }
